// Smoke-test the tools and the install guard without a Host: mount the plugin
// on a stub context, then run each registered tool and each guard case.
// Plain node is enough (built-ins only).
//
//   node scripts/try-tool.mjs [bundle-directory]
//
// The bundle-directory argument defaults to this repository and is what
// dsh_plugin_check inspects. dsh_plugin_new always writes to tmp/smoke-output,
// which is git-ignored.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { rm } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { apply } from '../tools/index.js'

const repo = fileURLToPath(new URL('..', import.meta.url))
const target = process.argv[2] ?? repo
const output = join(repo, 'tmp', 'smoke-output')

const registered = new Map()
const guards = []
const ctx = {
  effect: (body) => body(),
  get: () => undefined,
  tools: {
    register: (definition) => {
      registered.set(definition.name, definition)
      return () => registered.delete(definition.name)
    },
    guard: (guard) => {
      guards.push(guard)
      return () => guards.splice(guards.indexOf(guard), 1)
    },
  },
}

apply(ctx)
const names = [...registered.keys()].sort()
if (names.length !== 6) throw new Error(`expected 6 tools, got ${names.join(', ') || 'none'}`)
if (guards.length !== 1) throw new Error(`expected 1 guard, got ${guards.length}`)
console.log(`registered: ${names.join(', ')} (+1 guard)\n`)

const check = registered.get('dsh_plugin_check')
const checkValue = await check.execute({ path: target })
console.log(check.output.render({}, checkValue)[0].text)
console.log('')

await rm(output, { recursive: true, force: true })
const create = registered.get('dsh_plugin_new')
const createValue = await create.execute({
  dest: output,
  packageName: 'dsh-plugin-smoke',
  title: 'Smoke bundle',
  description: 'Generated by scripts/try-tool.mjs to prove the scaffolder produces a passing bundle.',
  withSkill: true,
}, {})
console.log(create.output.render({}, createValue)[0].text)

if (!createValue.checks.ok) throw new Error('the generated bundle did not pass its own structural check')
if (!checkValue.ok) throw new Error(`${target} failed its structural check`)

// The sandbox tool shares lib/sandbox.js with the CLI; try-sandbox.mjs covers the
// engine, this only proves the tool is wired to it and reports an empty project.
const sandbox = registered.get('dsh_sandbox')
const sandboxEmpty = await sandbox.execute({ action: 'list', project: join(repo, 'tmp', 'empty-project') }, {})
if (!sandboxEmpty.summary.includes('No sandboxes')) throw new Error(`dsh_sandbox list on an empty project said: ${sandboxEmpty.summary}`)
let sandboxUnknown = 'threw'
try {
  await sandbox.execute({ action: 'remove', name: 'nope', project: repo }, {})
  sandboxUnknown = 'did not throw'
} catch (error) {
  if (!/no sandbox/.test(error.message)) throw error
}
if (sandboxUnknown !== 'threw') throw new Error(`dsh_sandbox remove on an unknown sandbox: ${sandboxUnknown}`)

// The release tool shares lib/release.js with the CLI; try-release.mjs covers the
// engine, this only proves the tool is wired to it.
const release = registered.get('dsh_plugin_release')
const releaseReport = await release.execute({ action: 'check', path: repo }, {})
if (typeof releaseReport.summary !== 'string' || !releaseReport.summary.includes('pass')) {
  throw new Error(`dsh_plugin_release check said: ${releaseReport.summary}`)
}
if (releaseReport.data?.checks?.length === 0) throw new Error('dsh_plugin_release returned no checks')
console.log(`dsh_plugin_release: ${releaseReport.data.summary.pass} pass, ${releaseReport.data.summary.warn} warn, ${releaseReport.data.summary.fail} fail`)

// The UI tool needs a browser and a page; try-ui.mjs drives it for real. Here we
// only prove it is registered and that `close` is safe when nothing is running.
const ui = registered.get('dsh_plugin_ui')
const uiClose = await ui.execute({ action: 'close', port: 9334 }, {})
if (typeof uiClose.summary !== 'string') throw new Error('dsh_plugin_ui close returned no summary')
console.log(`dsh_plugin_ui: ${uiClose.summary}`)

// The project-check tool shares lib/checks.js with the CLI; try-checks.mjs
// covers the engine, this proves the tool runs this repository's own rules.
const project = registered.get('dsh_project_check')
const projectReport = await project.execute({ path: repo }, {})
if (projectReport.ok !== true) {
  throw new Error(`dsh_project_check on this repo: ${JSON.stringify(projectReport.checks.filter(item => item.status !== 'pass'))}`)
}
console.log(`dsh_project_check: ${projectReport.summary.pass} pass from ${projectReport.source.split(/[\\/]/).pop()}`)
console.log(`dsh_sandbox: ${sandboxEmpty.summary.split('\n')[0]}`)

// --- install guard ---------------------------------------------------------
const guard = guards[0]
const originalHome = process.env.DSH_HOME
const originalOverride = process.env.DSH_ALLOW_LOCAL_PLUGIN_INSTALL

function verdict(exec) {
  const result = guard(exec)
  return result === undefined ? 'allow' : 'deny'
}

const sandboxHome = join(repo, 'tmp', 'guard-sandbox', 'home')
mkdirSync(sandboxHome, { recursive: true })
writeFileSync(join(repo, 'tmp', 'guard-sandbox', 'sandbox.json'), JSON.stringify({ marker: 'dsh-plugin-creator/sandbox' }))

const cases = [
  ['plugin_manager install_bundle link:', { name: 'plugin_manager', arguments: { action: 'install_bundle', target: 'link:E:/Workplace/x' } }, 'deny'],
  ['plugin_manager install_bundle windows absolute path', { name: 'plugin_manager', arguments: { action: 'install_bundle', target: 'E:/Workplace/x' } }, 'deny'],
  ['plugin_manager install_bundle posix absolute path', { name: 'plugin_manager', arguments: { action: 'install_bundle', target: '/opt/plugins/x' } }, 'deny'],
  ['plugin_manager install_bundle unc path', { name: 'plugin_manager', arguments: { action: 'install_bundle', target: '\\\\server\\share\\x' } }, 'deny'],
  ['plugin_manager install_bundle relative path', { name: 'plugin_manager', arguments: { action: 'install_bundle', target: './x' } }, 'deny'],
  ['plugin_manager install_bundle registry spec', { name: 'plugin_manager', arguments: { action: 'install_bundle', target: 'dshmarket@1.84.1' } }, 'allow'],
  ['plugin_manager set_bundle', { name: 'plugin_manager', arguments: { action: 'set_bundle', target: 'link:E:/x' } }, 'allow'],
  ['pwsh dsh plugin add link: to the desktop profile', { name: 'pwsh', arguments: { command: 'dsh plugin --profile desktop add link:E:/Workplace/x' } }, 'deny'],
  ['pwsh dsh plugin add link: with no profile', { name: 'pwsh', arguments: { command: 'dsh plugin add link:E:/Workplace/x' } }, 'deny'],
  ['pwsh dsh plugin add link: to a sandbox profile', { name: 'pwsh', arguments: { command: 'dsh plugin --profile sb-default add link:E:/Workplace/x' } }, 'allow'],
  ['pwsh with a sandbox home', { name: 'pwsh', arguments: { command: '$env:DSH_HOME="E:/p/tmp/sandboxes/default/home"; dsh plugin --profile sb-default add link:E:/x' } }, 'allow'],
  ['pwsh reading a plugin manager log', { name: 'pwsh', arguments: { command: 'Get-Content log.txt | Select-String "dsh plugin"' } }, 'allow'],
  ['read tool', { name: 'read', arguments: { file_path: 'E:/x' } }, 'allow'],
]

process.env.DSH_HOME = join(repo, 'tmp', 'not-a-sandbox')
delete process.env.DSH_ALLOW_LOCAL_PLUGIN_INSTALL
const failures = []
for (const [label, exec, expected] of cases) {
  const actual = verdict(exec)
  if (actual !== expected) failures.push(`${label}: expected ${expected}, got ${actual}`)
}
console.log(`\nguard (current environment): ${cases.length - failures.length}/${cases.length} cases as expected`)

// Inside a sandbox host, the same local install must be allowed.
process.env.DSH_HOME = sandboxHome
const inSandbox = [
  ['plugin_manager install_bundle link: inside a sandbox', { name: 'plugin_manager', arguments: { action: 'install_bundle', target: 'link:E:/Workplace/x' } }, 'allow'],
  ['pwsh dsh plugin add link: inside a sandbox', { name: 'pwsh', arguments: { command: 'dsh plugin add link:E:/Workplace/x' } }, 'allow'],
]
for (const [label, exec, expected] of inSandbox) {
  const actual = verdict(exec)
  if (actual !== expected) failures.push(`${label}: expected ${expected}, got ${actual}`)
}
console.log(`guard (sandbox host): ${inSandbox.length} cases checked`)

// The documented release valve.
process.env.DSH_HOME = join(repo, 'tmp', 'not-a-sandbox')
process.env.DSH_ALLOW_LOCAL_PLUGIN_INSTALL = '1'
if (verdict({ name: 'plugin_manager', arguments: { action: 'install_bundle', target: 'link:E:/x' } }) !== 'allow') {
  failures.push('override: expected allow with DSH_ALLOW_LOCAL_PLUGIN_INSTALL=1')
}
console.log('guard (override): checked')

if (originalHome === undefined) delete process.env.DSH_HOME
else process.env.DSH_HOME = originalHome
if (originalOverride === undefined) delete process.env.DSH_ALLOW_LOCAL_PLUGIN_INSTALL
else process.env.DSH_ALLOW_LOCAL_PLUGIN_INSTALL = originalOverride
rmSync(join(repo, 'tmp', 'guard-sandbox'), { recursive: true, force: true })

if (failures.length > 0) {
  console.error(`\nGUARD FAILURES:\n- ${failures.join('\n- ')}`)
  process.exitCode = 1
} else {
  console.log('\nsmoke ok')
}
